"""Reading the SAP PM export and the planner's reference sheet.

The source workbook has two sheets:

``Rohdaten``   - ~69k rows x 69 columns, one row per *maintenance call*
                 generated by SAP PM for a piece of medical equipment.
``Zusatdaten`` - a hand-maintained sheet where the planner keeps teams,
                 headcount, absences, the working calendar, the daily
                 maintenance capacity per team and the activity code table.
                 Every block is a different set of columns inside the same
                 sheet, padded with NaN - hence the column-wise dropna below.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from ..config import Config
from ..domain import Absence, PlanningContext, Team


def load_reference(config: Config) -> dict:
    """Parse the planner's reference sheet into independent blocks."""
    sheet = pd.read_excel(config.data.workbook, sheet_name=config.data.reference_sheet)

    horizon = sheet[["Start", "Ende"]].dropna()
    start_date = pd.Timestamp(horizon["Start"].iloc[0])
    end_date = pd.Timestamp(horizon["Ende"].iloc[0])

    lead = sheet[["Vorsprung"]].dropna()
    max_lead_days = (
        int(lead["Vorsprung"].iloc[0]) if not lead.empty else config.planning.max_lead_days
    )

    teams = sheet[["Team.1", "Mitarbeiter"]].dropna()
    teams = teams.rename(columns={"Team.1": "team", "Mitarbeiter": "technician"})

    absences = sheet[["Urlaub / Langzeitausfall", "Von", "Bis"]].dropna()
    absences = absences.rename(
        columns={"Urlaub / Langzeitausfall": "technician", "Von": "start", "Bis": "end"}
    )
    absences["start"] = pd.to_datetime(absences["start"], dayfirst=True)
    absences["end"] = pd.to_datetime(absences["end"], dayfirst=True)

    calendar = sheet[["Datum"]].dropna()
    calendar["Datum"] = pd.to_datetime(calendar["Datum"])
    calendar = calendar[
        (calendar["Datum"] >= start_date) & (calendar["Datum"] <= end_date)
    ]

    capacity = sheet[["Gruppe", "Wartungszeiten"]].dropna()
    capacity = capacity.rename(columns={"Gruppe": "team", "Wartungszeiten": "daily_hours"})

    codes = sheet[["Abkürzungen", "Erklärung"]].dropna()
    activity_labels = dict(zip(codes["Abkürzungen"], codes["Erklärung"]))

    return {
        "start_date": start_date,
        "end_date": end_date,
        "max_lead_days": max_lead_days,
        "teams": teams,
        "absences": absences,
        "working_days": calendar["Datum"].sort_values().tolist(),
        "capacity": capacity,
        "activity_labels": activity_labels,
    }


def build_context(config: Config, reference: dict) -> PlanningContext:
    capacity = dict(
        zip(reference["capacity"]["team"], reference["capacity"]["daily_hours"])
    )
    teams: dict[str, Team] = {}
    for team_name, block in reference["teams"].groupby("team"):
        teams[team_name] = Team(
            name=team_name,
            technicians=block["technician"].tolist(),
            daily_hours=float(
                capacity.get(team_name, config.planning.default_daily_hours)
            ),
        )

    absences = [
        Absence(row.technician, row.start, row.end)
        for row in reference["absences"].itertuples()
    ]

    return PlanningContext(
        working_days=reference["working_days"],
        teams=teams,
        absences=absences,
        activity_labels=reference["activity_labels"],
        start_date=reference["start_date"],
        end_date=reference["end_date"],
        max_lead_days=reference["max_lead_days"],
        batching_window_days=config.planning.batching_window_days,
    )


def load_orders(config: Config) -> pd.DataFrame:
    """Read the raw maintenance calls, keeping only the relevant columns."""
    frame = pd.read_excel(
        config.data.workbook,
        sheet_name=config.data.orders_sheet,
        usecols=list(config.data.columns.values()),
    )
    frame = frame.rename(columns={v: k for k, v in config.data.columns.items()})
    # The group column is typed by hand in SAP: stray whitespace is common and
    # a missing group means the device has never been assigned to a team.
    frame["technician_group"] = (
        frame["technician_group"].astype("object").fillna("").astype(str).str.strip()
    )
    return frame


def workbook_exists(config: Config) -> bool:
    return Path(config.data.workbook).exists()
